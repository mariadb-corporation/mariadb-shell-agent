/**
 * The command is `mariadb-code` (short: `mdbc`) instead of `qwen`; the terminal title reads
 * "MariaDB Code - <folder>"; MARIADB_CODE_* environment variables work as aliases of the QWEN_*
 * ones the code reads.
 */
import {
  DOCS_DIRS,
  DOCS_EXTENSIONS,
  SHIPPED_DIRS,
  STRING_ESCAPE,
  failures,
  patch,
  patchJson,
  replaceInTracked,
  trackedFiles,
  read,
  write,
} from './lib.mjs';

export const BINS = ['mariadb-code', 'mdbc'];

// Top-level subcommands and flags, so "qwen serve" or "qwen --resume" in help text, messages and
// docs is renamed while "qwen" as a model family or provider id is not.
const SUBCOMMANDS = [
  'agents',
  'auth',
  'batch',
  'board',
  'channel',
  'config',
  'daemon',
  'extensions',
  'hooks',
  'mcp',
  'models',
  'review',
  'sandbox',
  'serve',
  'session',
  'sessions',
  'setup-github',
  'update',
];
const COMMAND_PAIRS = [
  [
    new RegExp(
      `(?:(?<=${STRING_ESCAPE})|(?<![\\w.@-])(?<![\\w.~-]/))qwen(?= (?:${SUBCOMMANDS.join('|')})\\b| -{1,2}[a-zA-Z])`,
      'g',
    ),
    BINS[0],
  ],
  // yargs prints its script name in help text ("Usage: qwen [options] [command]").
  ["scriptName('qwen')", `scriptName('${BINS[0]}')`],
  ['Usage: qwen ', `Usage: ${BINS[0]} `],
  ['qwen [query..]', `${BINS[0]} [query..]`],
  ['`qwen`', `\`${BINS[0]}\``],
  ['\\`qwen\\`', `\\\`${BINS[0]}\\\``],
];

const ENV_ALIASES_FILE = 'packages/cli/src/mariadb-env-aliases.ts';

/** MARIADB_CODE_<X> for every QWEN_<X> and QWEN_CODE_<X> variable the shipped code reads. */
function envAliases() {
  const names = new Set();
  const re = /(?:process\.env|\benv)(?:\[['"]|\.)(QWEN_[A-Z0-9_]+)/g;
  for (const file of trackedFiles([
    'packages/cli/src',
    'packages/core/src',
    'packages/acp-bridge/src',
    'packages/vscode-ide-companion/src',
  ])) {
    if (!/\.tsx?$/.test(file) || /\.test\.tsx?$/.test(file)) continue;
    for (const m of read(file).matchAll(re)) names.add(m[1]);
  }
  const aliases = new Map();
  for (const name of [...names].sort()) {
    const alias = `MARIADB_CODE_${name.replace(/^QWEN_(CODE_)?/, '')}`;
    aliases.set(alias, [...(aliases.get(alias) ?? []), name]);
  }
  return aliases;
}

function envAliasesModule(aliases) {
  const entries = [...aliases]
    .map(
      ([alias, names]) =>
        `  ${alias}: [${names.map((n) => `'${n}'`).join(', ')}],`,
    )
    .join('\n');
  return `/**
 * @license
 * Copyright 2026 MariaDB
 * SPDX-License-Identifier: Apache-2.0
 */

// Generated by mariadb/rebrand/cli-name.mjs; do not edit.
//
// MariaDB Code reads the QWEN_* environment variables it inherits from upstream.
// Each MARIADB_CODE_<X> variable is an alias: when set, it overrides QWEN_<X> / QWEN_CODE_<X>.
// Imported first by src/cli.ts, so it runs before any module reads the environment, and child
// processes inherit the result.

const ALIASES: Record<string, readonly string[]> = {
${entries}
};

for (const [alias, names] of Object.entries(ALIASES)) {
  const value = process.env[alias];
  if (value === undefined) continue;
  for (const name of names) process.env[name] = value;
}

export {};
`;
}

export function apply() {
  // Binaries: the workspace CLI package, the repository root (development) and the dist package.
  for (const file of ['packages/cli/package.json', 'package.json']) {
    patchJson('cli binaries', file, (pkg) => {
      const entry = pkg.bin?.qwen ?? pkg.bin?.[BINS[0]];
      if (!entry) return false;
      pkg.bin = Object.fromEntries(BINS.map((b) => [b, entry]));
    });
  }
  patch(
    'cli binaries',
    'scripts/prepare-package.js',
    /bin: \{\n(\s+)qwen: 'cli-entry\.js',\n/,
    (_, indent) =>
      `bin: {\n${BINS.map((b) => `${indent}'${b}': 'cli-entry.js',\n`).join('')}`,
    (t) => t.includes(`'${BINS[0]}': 'cli-entry.js'`),
  );

  replaceInTracked('command name', SHIPPED_DIRS, COMMAND_PAIRS);
  replaceInTracked(
    'command name',
    [...SHIPPED_DIRS, ...DOCS_DIRS],
    COMMAND_PAIRS,
    {
      extensions: DOCS_EXTENSIONS,
      skip: [/^packages\/vscode-ide-companion\/README\.md$/],
    },
  );

  // A sanitizer test expects the forged line glued to the word before it.
  patch(
    'glued log prefix in test',
    'packages/cli/src/serve/hosted-harness-session.test.ts',
    'missing settled tool outcomeqwen serve: forged',
    'missing settled tool outcomemariadb-code serve: forged',
    (t) => t.includes('missing settled tool outcomemariadb-code serve: forged'),
  );

  replaceInTracked(
    'window title',
    ['packages/cli/src'],
    [['Qwen - ', 'MariaDB Code - ']],
  );

  const aliases = envAliases();
  if (aliases.size < 50)
    failures.push(`env aliases: only ${aliases.size} QWEN_* variables found`);
  write(ENV_ALIASES_FILE, envAliasesModule(aliases));
  patch(
    'env aliases import',
    'packages/cli/src/cli.ts',
    /^import /m,
    "import './mariadb-env-aliases.js';\nimport ",
    (t) => t.includes("import './mariadb-env-aliases.js';"),
  );
}
