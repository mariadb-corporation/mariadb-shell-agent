#!/bin/bash
# Rebases the fork onto the newest upstream Qwen Code and regenerates the branding commit.
#
#   mariadb/sync-upstream.sh [--to <upstream rev>] [--verify] [--push]
#
# Branch layout of main (see mariadb/README.md):
#   upstream/main  <-  fork commits (mariadb/ only, or real fixes)  <-  "MariaDB branding (generated)"
# The generated commit is dropped, the fork commits are replayed onto upstream/main,
# mariadb/rebrand.mjs runs on the fresh upstream files and its result is committed on top again.
# Also run it after committing a change to mariadb/, to regenerate the branding.
# Afterwards mariadb/check-leaks.mjs must find no old names or Alibaba hosts. --verify also runs
# the test gate (mariadb/verify.mjs, about an hour). --push force-pushes main to NAS (the history
# is rewritten), only when those checks passed. --to rebases onto an older upstream commit than
# upstream/main, e.g. while upstream's main does not build.
set -euo pipefail
cd "$(dirname "$0")/.."

BRAND_SUBJECT='MariaDB branding (generated by mariadb/rebrand.mjs)'
PUSH=false
VERIFY=false
TARGET=upstream/main
while [ $# -gt 0 ]; do
  case "$1" in
    --push) PUSH=true ;;
    --verify) VERIFY=true ;;
    --to) TARGET=$2; shift ;;
    *) echo "usage: $0 [--to <upstream rev>] [--verify] [--push]" >&2; exit 1 ;;
  esac
  shift
done

[ "$(git branch --show-current)" = main ] || { echo "check out main first" >&2; exit 1; }
[ -z "$(git status --porcelain)" ] || { echo "working tree not clean; commit or stash first" >&2; exit 1; }

git fetch upstream
OLD=$(git rev-parse HEAD)
BASE=$(git merge-base HEAD upstream/main)
TARGET=$(git rev-parse --verify "$TARGET^{commit}")
# Fork commits, oldest first, without the generated branding commit(s).
FORK=$(git log --reverse --format='%H%x09%s' "$BASE..HEAD" |
  awk -F'\t' -v s="$BRAND_SUBJECT" '$2 != s { print $1 }')
echo "previous main: $OLD (git reset --hard $OLD to undo)"

git reset -q --hard "$TARGET"
for c in $FORK; do
  git cherry-pick "$c" || {
    echo "conflict replaying $c: resolve, 'git cherry-pick --continue', replay the rest of:" >&2
    echo "$FORK" >&2
    echo "then run 'node mariadb/rebrand.mjs' and commit the result as \"$BRAND_SUBJECT\"" >&2
    exit 1
  }
done

node mariadb/rebrand.mjs
git add -A
git commit -q -m "$BRAND_SUBJECT" -m "Upstream: $(git rev-parse --short "$TARGET") ($(git log -1 --format=%cs "$TARGET"))"
echo "main is now $(git log -1 --format=%h): upstream $(git rev-parse --short "$TARGET") + $(echo "$FORK" | grep -c .) fork commit(s) + branding"

corepack pnpm install --frozen-lockfile

node mariadb/check-leaks.mjs
if $VERIFY; then
  node mariadb/verify.mjs
fi

if $PUSH; then
  git push --force-with-lease NAS main
fi
